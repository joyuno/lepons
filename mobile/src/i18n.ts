const language = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2);
export const locale = language === "zh" ? "zh" : language === "en" ? "en" : "ko";
export const t: Strings = locale === "zh" ? zh : locale === "en" ? en : ko;
export type StringKey = keyof Strings;

/** "{count}" and friends filled in; "{n|file|files}" is the word for that many (English: 1 is singular). */
export const fmt = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)(?:\|([^|}]*)\|([^}]*))?\}/g, (all, name: string, one?: string, many?: string) =>
    !(name in values) ? all : one === undefined ? String(values[name]) : Number(values[name]) === 1 ? one : many!);

/**
 * "3분 전", "2 h ago": how long ago, in the app's language. Not
 * Intl.RelativeTimeFormat, which Hermes may not carry.
 */
const units = {
  ko: { now: "방금", minute: "{n}분 전", hour: "{n}시간 전", day: "{n}일 전" },
  en: { now: "just now", minute: "{n} min ago", hour: "{n} h ago", day: "{n} d ago" },
  zh: { now: "刚刚", minute: "{n} 分钟前", hour: "{n} 小时前", day: "{n} 天前" },
}[locale];
export function ago(at: number): string {
  const seconds = Math.max(0, Math.round((Date.now() - at) / 1000));
  for (const [unit, size] of [["day", 86400], ["hour", 3600], ["minute", 60]] as const) {
    if (seconds >= size) return fmt(units[unit], { n: Math.floor(seconds / size) });
  }
  return units.now;
}
