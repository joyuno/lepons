import { exec as execCallback } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir, platform } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";

import { agents, signedInFrom, type AgentKind } from "../agent/agents.ts";
import type { AgentAccount } from "../shared/ipc.ts";
import { inLoginShell, probeScript, probeTimeoutMs, readProbe } from "../ssh/capabilities.ts";
import { agentEndpoint } from "../ssh/identity.ts";
import { generateKeyPair } from "../ssh/keys.ts";
import { leponsIdentityName } from "../ssh/ssh-config.ts";

// A fixed command with no interpolated arguments: execFile with shell:true
// concatenates rather than escapes, which Node flags as a security hazard even
// when the arguments are constant.
const run = promisify(execCallback);

export interface PublicKey {
  name: string;
  value: string;
}

export interface SetupInfo {
  /** Keys this machine can offer a node, so the guide can show one to copy. */
  publicKeys: PublicKey[];
  agentRunning: boolean;
  /** Version per agent; absent for one that is not installed here. */
  agentVersions: Partial<Record<AgentKind, string>>;
  /** Each agent's official installer for this operating system. */
  installCommands: Record<AgentKind, string>;
}

/**
 * This app's own key, made once and then left alone.
 *
 * Generated rather than derived: a key that came from an address or an account
 * name could be regenerated by anyone who knows either, which is not a key.
 * Made in-process with ssh2 rather than by running `ssh-keygen`, which a
 * Windows PC without the OpenSSH client does not have. The files are the
 * same OpenSSH pair ssh-keygen would write, so the operator can inspect,
 * back up or delete them like any other.
 *
 * Never overwrites. A machine that already has this key -- including one set
 * up by hand before the app did it -- keeps exactly the key its nodes already
 * trust, because replacing it would lock the operator out of every one.
 */
export async function ensureLeponsKey(): Promise<void> {
  const directory = join(homedir(), ".ssh");
  const path = join(directory, leponsIdentityName);
  if (existsSync(path)) return;
  try {
    mkdirSync(directory, { recursive: true, mode: 0o700 });
    // No passphrase: the app opens connections unattended, and a prompt it
    // would have to cache in memory anyway buys nothing over file permissions.
    const pair = generateKeyPair({ comment: "lepons" });
    // "wx": a key that appeared meanwhile is kept, never overwritten.
    writeFileSync(path, `${pair.private}\n`, { mode: 0o600, flag: "wx" });
    writeFileSync(`${path}.pub`, `${pair.public}\n`, { mode: 0o644 });
  } catch {
    // Falls back to whatever keys the machine already has; the guide
    // reports what it finds rather than claiming a key exists.
  }
}

/**
 * This app's key first, then anything else in ~/.ssh.
 *
 * Order is the point: the guide shows `publicKeys[0]`, and that has to be the
 * key resolveIdentity will actually offer, or the guide teaches a setup that
 * cannot work.
 */
function readPublicKeys(): PublicKey[] {
  const directory = join(homedir(), ".ssh");
  try {
    const keys = readdirSync(directory)
      .filter((name) => name.endsWith(".pub"))
      .map((name) => ({
        name,
        value: readFileSync(join(directory, name), "utf8").trim(),
      }))
      .filter((key) => key.value !== "");
    const ours = `${leponsIdentityName}.pub`;
    return keys.sort((a, b) => Number(b.name === ours) - Number(a.name === ours));
  } catch {
    return [];
  }
}

async function versionOf(kind: AgentKind): Promise<string | undefined> {
  try {
    const { stdout } = await run(agents[kind].versionCommand, { timeout: 5000 });
    return stdout.trim().split("\n")[0];
  } catch {
    return undefined;
  }
}

async function signedInOf(kind: AgentKind): Promise<boolean | undefined> {
  const command = agents[kind].loginStatusCommand;
  if (command === undefined) return undefined;
  try {
    const { stdout, stderr } = await run(command, { timeout: 5000 });
    return signedInFrom(0, `${stdout}${stderr}`);
  } catch (error) {
    const failed = error as { code?: unknown; stdout?: string; stderr?: string };
    return typeof failed.code === "number" ? signedInFrom(failed.code, `${failed.stdout ?? ""}${failed.stderr ?? ""}`) : undefined;
  }
}

/**
 * This PC asked the way a remote one is (probeScript, remoteLoginScript):
 * through the account's login + interactive shell, which is where a terminal
 * and a session here find the agents. Off Windows the app's own PATH is the
 * wrong one: opened from Finder or the Dock it is launchd's
 * /usr/bin:/bin:/usr/sbin:/sbin, so claude and codex under nvm, Homebrew or
 * ~/.local/bin read as not installed. `-l` alone is not enough either: nvm
 * sits in ~/.zshrc (inLoginShell). Undefined: the shell never answered.
 */
async function askLoginShell(script: string): Promise<string | undefined> {
  try {
    return (await run(inLoginShell(script), { timeout: probeTimeoutMs })).stdout;
  } catch (error) {
    // Cut off or exited non-zero, it may still have said what it found.
    return (error as { stdout?: string }).stdout || undefined;
  }
}

/** What the AI accounts tab shows: each agent's version here, and its sign-in where knowable. */
export async function agentAccounts(): Promise<AgentAccount[]> {
  if (platform() !== "win32") return remoteAgentAccounts(await askLoginShell(`${probeScript}; ${remoteLoginScript}`));
  return Promise.all((Object.keys(agents) as AgentKind[]).map(async (kind): Promise<AgentAccount> => {
    const version = await versionOf(kind);
    if (version === undefined || version === "") return { kind };
    const signedIn = await signedInOf(kind);
    return signedIn === undefined ? { kind, version } : { kind, version, signedIn };
  }));
}

/**
 * Run after the probe on the AI accounts tab: each installed agent's
 * loginStatusCommand, its printout folded onto one `kind-login:` line that
 * ends in the exit code. Each is killed after 5 s, so a CLI that hangs costs
 * those seconds and reads as unknown instead of stalling the tab.
 */
export const remoteLoginScript = Object.values(agents).flatMap((agent) => {
  const command = agent.loginStatusCommand;
  if (command === undefined) return [];
  return [
    // To a file, not a pipe: a child the kill misses would hold a pipe open.
    `command -v ${command.split(" ")[0]} >/dev/null 2>&1 && f=$(mktemp) && ( ` +
    // In its own process group (set -m), so the kill reaches a node an npm shim started too.
    // zsh refuses set -m in a subshell and drops the whole subshell for trying -- every
    // Mac's sign-in read as unknown -- so it is tried in a throwaway one first; without
    // it the kill takes the command's children (pkill -P) and then the command. KILL,
    // not TERM: npm's codex.js catches TERM and exits 0, which read as signed in.
    `(set -m) 2>/dev/null && set -m; ${command} >"$f" 2>&1 </dev/null & p=$!; (sleep 5; kill -9 -- -$p || { pkill -9 -P $p; kill -9 $p; }) >/dev/null 2>&1 & k=$!; wait $p; r=$?; kill $k 2>/dev/null; ` +
    `echo "${agent.kind}-login:$(tr '\\r\\n' '  ' <"$f") rc:$r"; rm -f "$f" )`,
  ];
}).join("; ");

/** A `kind-login:` line read the way signedInOf reads one here; killed (over 128) or absent is unknown. */
function remoteSignedIn(kind: AgentKind, output: string): boolean | undefined {
  const line = new RegExp(`^${kind}-login:(.*) rc:(\\d+)\\s*$`, "m").exec(output);
  if (!line || agents[kind].loginStatusCommand === undefined) return undefined;
  const code = Number(line[2]);
  return code > 128 ? undefined : signedInFrom(code, line[1]!);
}

/**
 * A remote PC's agents from its probe's printout (undefined: not reached).
 * One its shell never got to report is unknown, not missing, so the tab
 * does not offer to install what may already be there.
 */
export function remoteAgentAccounts(output: string | undefined): AgentAccount[] {
  const read = output === undefined ? undefined : readProbe(output);
  return (Object.keys(agents) as AgentKind[]).map((kind): AgentAccount => {
    const version = read?.capabilities.agentVersions[kind];
    if (version === undefined) return read?.shellRead ? { kind } : { kind, unknown: true };
    const signedIn = remoteSignedIn(kind, output!);
    return signedIn === undefined ? { kind, version } : { kind, version, signedIn };
  });
}

/**
 * What the operator needs to know before anything will connect.
 *
 * Gathered rather than described: the guide shows this machine's actual public
 * key and which agents are actually here, because a setup page that merely
 * explains the steps leaves the operator to check each one by hand -- which is
 * the step people skip.
 *
 * Both agents are reported, not just the one this machine happens to use. A
 * guide that mentions only Claude reads as though Codex is unsupported, and an
 * operator who has Codex installed would go looking for something to install.
 */
export async function collectSetupInfo(): Promise<SetupInfo> {
  const posix = platform() !== "win32";
  await ensureLeponsKey();
  const kinds = Object.keys(agents) as AgentKind[];
  // Off Windows from the login shell, as agentAccounts asks. A shell that never
  // got to the end is no answer: the app's own PATH then fills in, as before, so
  // the guide does not offer to reinstall what that shell could not report.
  const probe = posix ? readProbe((await askLoginShell(probeScript)) ?? "") : undefined;
  const found = probe?.shellRead ? [] : await Promise.all(kinds.map((kind) => versionOf(kind)));
  const agentVersions: Partial<Record<AgentKind, string>> = probe?.capabilities.agentVersions ?? {};
  kinds.forEach((kind, index) => {
    const version = found[index];
    if (version !== undefined && version !== "") agentVersions[kind] = version;
  });

  return {
    publicKeys: readPublicKeys(),
    agentRunning: agentEndpoint() !== undefined,
    agentVersions,
    installCommands: Object.fromEntries(
      kinds.map((kind) => [kind, posix ? agents[kind].install.posix : agents[kind].install.win32]),
    ) as Record<AgentKind, string>,
  };
}
