/** Exported so a test can hold the three side by side. */
export const dictionaries: Record<Locale, Dictionary> = { ko, en, zh };

let active: Locale = "ko";

export function setLocale(locale: Locale): void {
  active = locale;
}

/**
 * Dates and times in the chosen language -- 오후 3:40, 3:40 PM, 下午3:40 --
 * rather than the OS's, which is what an empty locale list gave. The time
 * zone stays the PC's own: a reset time shown in another zone than the
 * clock on the wall would be wrong, whatever the language.
 */
const dateTags: Record<Locale, string> = { ko: "ko-KR", en: "en-US", zh: "zh-CN" };
export function formatDate(at: number | Date, options: Intl.DateTimeFormatOptions): string {
  // 12-hour everywhere, so each language says its own word for the half of
  // the day; Chinese would otherwise default to a bare 15:40.
  const hour12 = options.hour !== undefined ? { hour12: true } : {};
  return new Date(at).toLocaleString(dateTags[active], { ...options, ...hour12 });
}

export function currentLocale(): Locale {
  return active;
}

export function isLocale(value: unknown): value is Locale {
  return value === "ko" || value === "en" || value === "zh";
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const template = dictionaries[active][key] ?? ko[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}
